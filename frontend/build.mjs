// Build the card into the integration's www/ folder, which it serves.
//
//   node build.mjs          one build
//   node build.mjs --watch  rebuild on change
//   node build.mjs --test   build a scratch copy and the pure modules for the
//                           tests, leaving the served file alone
import * as esbuild from "esbuild";

const watch = process.argv.includes("--watch");
const test = process.argv.includes("--test");
// The integration's www/ by default -- which a live Home Assistant serves --
// or, for the tests, a scratch copy nobody loads.
const outfile = test
  ? ".cache/hockey-match-card.js"
  : "../custom_components/swedish_hockey/www/hockey-match-card.js";

const card = {
  entryPoints: ["src/hockey-match-card.ts"],
  outfile,
  bundle: true,
  format: "esm",
  target: "es2021",
  // Readable output: this file is what a browser's debugger shows, and what a
  // person looking in the integration's www/ folder finds.
  minify: false,
  legalComments: "eof",
  banner: {
    js:
      "// hockey-match-card -- GENERATED from frontend/src by `npm run build`.\n" +
      "// Do not edit this file; edit the TypeScript and rebuild.",
  },
  logLevel: "info",
};

// The pure modules, as one ESM file the tests can import without a DOM.
const internals = {
  entryPoints: ["src/internals.ts"],
  outfile: ".cache/internals.mjs",
  bundle: true,
  format: "esm",
  target: "es2021",
  platform: "neutral",
  logLevel: "warning",
};

if (watch) {
  const ctx = await esbuild.context(card);
  await ctx.watch();
} else {
  await esbuild.build(card);
  if (test) await esbuild.build(internals);
}
